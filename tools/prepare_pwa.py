"""Create deterministic release metadata; optionally stage only public runtime files."""
from pathlib import Path
import argparse
import hashlib
import json
import shutil

ROOT = Path(__file__).resolve().parent.parent


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, help='New empty deployment directory (optional)')
    args = parser.parse_args()
    files = [ROOT / name for name in ('index.html', 'manifest.webmanifest', 'js/app.js', 'js/data-loader.js', 'js/pwa.js', 'js/runtime-status.js')]
    for folder, pattern in [('css', '*.css'), ('icons', '*.png')]:
        files.extend((ROOT / folder).glob(pattern))
    # Include only datasets explicitly referenced by the runtime catalog.
    catalog_path = ROOT / 'data/catalog.json'
    files.append(catalog_path)
    catalog = json.loads(catalog_path.read_text(encoding='utf-8'))
    for spec in catalog['levelDatasets'].values():
        names = spec.get('files') or [spec['file']]
        for level in catalog['levels']:
            files.extend(ROOT / 'data' / level / name for name in names)
    files.extend(ROOT / 'data' / name for name in catalog['sharedDatasets'].values())
    files = sorted(set(files))
    assets = [{'path': p.relative_to(ROOT).as_posix(), 'sha': digest(p)} for p in files]
    signature = json.dumps({'assets': assets, 'worker': digest(ROOT / 'sw.js')}, sort_keys=True, separators=(',', ':'))
    version = hashlib.sha256(signature.encode()).hexdigest()[:20]
    release = json.dumps({'version': version, 'assets': assets}, ensure_ascii=True, separators=(',', ':'))
    if args.output:
        dest = args.output.resolve()
        if dest == ROOT or dest in ROOT.parents or (dest.exists() and any(dest.iterdir())):
            raise SystemExit('Choose a new empty output directory.')
        dest.mkdir(parents=True, exist_ok=True)
        for source in files + [ROOT / 'sw.js']:
            target = dest / source.relative_to(ROOT)
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source, target)
    else:
        dest = ROOT
    (dest / 'pwa-assets.js').write_text('// Generated by tools/prepare_pwa.py. Do not edit.\nself.WORTDUELL_RELEASE = ' + release + ';\n', encoding='utf-8')
    print(f'WortDuell release {version}: {len(assets)} offline assets')

if __name__ == '__main__':
    main()
